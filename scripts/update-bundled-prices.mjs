/**
 * Regenerates src/context/price-catalog-bundled.ts — the snapshot of LiteLLM's
 * public model price catalog that ships inside graft, so models graft's own
 * table does not list are priced out of the box, before (or without) any
 * `graft prices update`.
 *
 * Fetches the SAME URL `graft prices update` uses and reduces it with the SAME
 * parser (`parseLiteLlmCatalog`), so a bundled price and a freshly updated one
 * can never disagree about filtering or keys. The request is one anonymous GET
 * of LiteLLM's public catalog: it carries nothing about the user, the machine
 * or the repo.
 *
 * Run: npm run prices:bundle
 *  (= node --import tsx scripts/update-bundled-prices.mjs)
 *  Strict: any failure exits 1 and leaves the snapshot untouched.
 *
 * `npm run build` (and so `prepublishOnly`) runs it first (`build:prices`) with
 * `--soft`, so every build of graft compiles the latest LiteLLM prices into
 * dist/. In soft mode a failed download (offline, proxy, HTTP error, bad JSON)
 * only prints a warning and the build continues with the snapshot already
 * checked in. `prepare` (npm install / npm ci, the Dockerfile) runs
 * `build:code` instead: installing dependencies never reaches the network for
 * prices or rewrites this tracked file.
 *
 * A catalog listing under 80% of the current snapshot's models is refused as
 * broken or partial; `--force` accepts it (npm run prices:bundle -- --force).
 *
 * GRAFT_SKIP_PRICES_BUNDLE=1 skips the download entirely (offline builds,
 * reproducible builds of an older commit).
 *
 * When the regenerated file differs from the current one only in fetchedAt
 * (same models, same prices), the file is left as is, so a build does not
 * dirty the working tree when LiteLLM has not changed.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outFile = join(repoRoot, "src", "context", "price-catalog-bundled.ts");
const soft = process.argv.includes("--soft");
const force = process.argv.includes("--force");
/** A fresh catalog listing fewer than this share of the current snapshot's models is refused. */
const MIN_KEPT_SHARE = 0.8;

const HEADER =
  "/**\n" +
  " * GENERATED by scripts/update-bundled-prices.mjs (`npm run prices:bundle`, also run\n" +
  " * by `npm run build`) — do not edit by hand. A reduced snapshot of LiteLLM's public\n" +
  " * price catalog (input-side rates only, $/Mtok, keyed by canonicalModelKey) that\n" +
  " * ships with graft, so models its built-in table does not list are priced before\n" +
  " * any `graft prices update`.\n" +
  " */\n" +
  "import type { PriceCatalog } from './price-catalog.js';\n\n";

function render(catalog) {
  const keys = Object.keys(catalog.models).sort();
  const rows = keys.map((k) => `    ${JSON.stringify(k)}: ${JSON.stringify(catalog.models[k])},`);
  return (
    HEADER +
    "export const BUNDLED_PRICE_CATALOG: PriceCatalog = {\n" +
    "  version: 1,\n" +
    "  source: 'LiteLLM',\n" +
    `  url: ${JSON.stringify(catalog.url)},\n` +
    `  fetchedAt: ${JSON.stringify(catalog.fetchedAt)},\n` +
    "  models: {\n" +
    rows.join("\n") +
    (rows.length ? "\n" : "") +
    "  },\n" +
    "};\n"
  );
}

/** A rendered snapshot without its fetchedAt line, to tell a real change from a re-fetch. */
function withoutFetchedAt(text) {
  return text.replace(/\r\n/g, "\n").replace(/^ {2}fetchedAt: .*\n/m, "");
}

/** Soft mode: warn and keep the checked-in snapshot. Strict mode: fail. */
function fail(message) {
  if (soft) {
    console.warn(`⚠ bundled LiteLLM prices not refreshed: ${message}`);
    console.warn(`  the build continues with the snapshot already in ${outFile}`);
    process.exit(0);
  }
  console.error(`✗ ${message}`);
  process.exit(1);
}

const skip = (process.env.GRAFT_SKIP_PRICES_BUNDLE ?? "").trim().toLowerCase();
if (skip !== "" && skip !== "0" && skip !== "false") {
  console.log("· GRAFT_SKIP_PRICES_BUNDLE is set: keeping the bundled LiteLLM price snapshot as is");
  process.exit(0);
}

// price-catalog.ts imports the bundled module, so it has to exist before the
// parser can be loaded on a fresh checkout.
if (!existsSync(outFile)) {
  writeFileSync(
    outFile,
    render({ url: "", fetchedAt: new Date(0).toISOString(), models: {} }),
  );
}

const { LITELLM_PRICES_URL, parseLiteLlmCatalog } = await import(
  pathToFileURL(join(repoRoot, "src", "context", "price-catalog.ts")).href
);

let body;
try {
  const res = await fetch(LITELLM_PRICES_URL, {
    method: "GET",
    credentials: "omit",
    redirect: "follow",
    signal: AbortSignal.timeout(soft ? 30_000 : 60_000),
  });
  if (!res.ok) fail(`HTTP ${res.status} from ${LITELLM_PRICES_URL}`);
  body = await res.text();
} catch (err) {
  const cause = err?.cause?.code ?? err?.cause?.message;
  fail(`could not download ${LITELLM_PRICES_URL}: ${err?.message ?? err}${cause ? ` (${cause})` : ""}`);
}

let json;
try {
  json = JSON.parse(body);
} catch {
  fail(`${LITELLM_PRICES_URL} did not return valid JSON`);
}

let catalog;
try {
  catalog = parseLiteLlmCatalog(json, new Date().toISOString(), LITELLM_PRICES_URL);
} catch (err) {
  fail(`could not read the LiteLLM catalog: ${err?.message ?? err}`);
}

const count = Object.keys(catalog.models).length;
// parseLiteLlmCatalog already refuses an empty reduction. A sharp drop is the
// other sign of a broken or partial upstream catalog: refuse it too, so it is
// never compiled into a build (or a publish) unseen. Upstream retiring a few
// models stays well inside the margin; --force accepts a real shrink.
const { BUNDLED_PRICE_CATALOG: previous } = await import(pathToFileURL(outFile).href);
const before = Object.keys(previous.models).length;
if (!force && before > 0 && count < before * MIN_KEPT_SHARE) {
  fail(
    `the LiteLLM catalog shrank from ${before} to ${count} priced models; ` +
      "the snapshot was not replaced (accept it with: npm run prices:bundle -- --force)",
  );
}

const next = render(catalog);
if (withoutFetchedAt(readFileSync(outFile, "utf8")) === withoutFetchedAt(next)) {
  console.log(`✓ bundled LiteLLM prices already current (${count} models, unchanged since the last snapshot)`);
  process.exit(0);
}

writeFileSync(outFile, next);
console.log(
  `✓ bundled LiteLLM prices for ${count} models ` +
    `(fetched ${catalog.fetchedAt}) into ${outFile}`,
);
