/**
 * Regenerates src/context/price-catalog-bundled.ts — the snapshot of LiteLLM's
 * public model price catalog that ships inside graft, so models graft's own
 * table does not list are priced out of the box, before (or without) any
 * `graft prices update`.
 *
 * Fetches the SAME URL `graft prices update` uses and reduces it with the SAME
 * parser (`parseLiteLlmCatalog`), so a bundled price and a freshly updated one
 * can never disagree about filtering or keys.
 *
 * Run: npm run prices:bundle
 *  (= node --import tsx scripts/update-bundled-prices.mjs)
 */
import { existsSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outFile = join(repoRoot, "src", "context", "price-catalog-bundled.ts");

const HEADER =
  "/**\n" +
  " * GENERATED by scripts/update-bundled-prices.mjs (`npm run prices:bundle`) — do not\n" +
  " * edit by hand. A reduced snapshot of LiteLLM's public price catalog (input-side\n" +
  " * rates only, $/Mtok, keyed by canonicalModelKey) that ships with graft, so models\n" +
  " * its built-in table does not list are priced before any `graft prices update`.\n" +
  " */\n" +
  "import type { PriceCatalog } from './price-catalog.js';\n\n";

function render(catalog) {
  const keys = Object.keys(catalog.models).sort();
  const rows = keys.map((k) => `    ${JSON.stringify(k)}: ${JSON.stringify(catalog.models[k])},`);
  return (
    HEADER +
    "export const BUNDLED_PRICE_CATALOG: PriceCatalog = {\n" +
    "  version: 1,\n" +
    "  source: 'LiteLLM',\n" +
    `  url: ${JSON.stringify(catalog.url)},\n` +
    `  fetchedAt: ${JSON.stringify(catalog.fetchedAt)},\n` +
    "  models: {\n" +
    rows.join("\n") +
    (rows.length ? "\n" : "") +
    "  },\n" +
    "};\n"
  );
}

// price-catalog.ts imports the bundled module, so it has to exist before the
// parser can be loaded on a fresh checkout.
if (!existsSync(outFile)) {
  writeFileSync(
    outFile,
    render({ url: "", fetchedAt: new Date(0).toISOString(), models: {} }),
  );
}

const { LITELLM_PRICES_URL, parseLiteLlmCatalog } = await import(
  pathToFileURL(join(repoRoot, "src", "context", "price-catalog.ts")).href
);

const res = await fetch(LITELLM_PRICES_URL, {
  method: "GET",
  credentials: "omit",
  redirect: "follow",
  signal: AbortSignal.timeout(60_000),
});
if (!res.ok) {
  console.error(`✗ HTTP ${res.status} from ${LITELLM_PRICES_URL}`);
  process.exit(1);
}
const json = JSON.parse(await res.text());
const catalog = parseLiteLlmCatalog(json, new Date().toISOString(), LITELLM_PRICES_URL);
writeFileSync(outFile, render(catalog));
console.log(
  `✓ bundled LiteLLM prices for ${Object.keys(catalog.models).length} models ` +
    `(fetched ${catalog.fetchedAt}) into ${outFile}`,
);
